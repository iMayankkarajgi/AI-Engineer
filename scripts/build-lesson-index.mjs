// Writes api/_lessons.js: one import per lesson file, so the lesson function
// (api/lesson.js) is packaged with every lesson on any host.
import fs from 'node:fs';

const files = fs.readdirSync('src/course/lessons').filter(f => f.endsWith('.js')).sort();
const lines = files.map((f, i) => `import l${i} from '../src/course/lessons/${f}';`);
fs.writeFileSync('api/_lessons.js', `// Generated by scripts/build-lesson-index.mjs. Do not edit.\n${lines.join('\n')}\nexport const lessons = Object.fromEntries([${files.map((_, i) => `l${i}`).join(', ')}].map(l => [l.id, l]));\n`);
console.log(`wrote api/_lessons.js (${files.length} lessons)`);
