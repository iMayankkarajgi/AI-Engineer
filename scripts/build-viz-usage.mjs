// Writes src/course/vizUsage.js: for each widget, the lessons that embed it.
// Run after adding or editing lessons: node scripts/build-viz-usage.mjs
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
import { lessonIds } from '../src/course/curriculum.js';

const map = {};
const walk = (blocks, id) => (blocks || []).forEach(b => {
  if (b.type === 'viz') (map[b.name] ||= []).includes(id) || map[b.name].push(id);
  if (b.type === 'deeper') walk(b.blocks, id);
  if (b.type === 'tabs') b.items.forEach(t => walk(t.blocks, id));
});
for (const id of lessonIds) {
  const file = `src/course/lessons/${id}.js`;
  if (!fs.existsSync(file)) continue;
  const L = (await import(pathToFileURL(file).href)).default;
  L.sections.forEach(s => walk(s.blocks, id));
}
fs.writeFileSync('src/course/vizUsage.js', `// Generated by scripts/build-viz-usage.mjs\nexport const vizUsage = ${JSON.stringify(map, null, 1)};\n`);
console.log(Object.keys(map).length, 'widgets used');
