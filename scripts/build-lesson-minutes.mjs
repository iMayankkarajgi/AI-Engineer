// Writes src/course/lessonMinutes.js: reading time per lesson, taken from the
// lesson files, so pages can state course length without loading every lesson.
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const dir = path.resolve('src/course/lessons');
const out = {};
for (const file of fs.readdirSync(dir).filter(f => f.endsWith('.js')).sort()) {
  const lesson = (await import(pathToFileURL(path.join(dir, file)).href)).default;
  out[lesson.id] = lesson.minutes;
}
fs.writeFileSync('src/course/lessonMinutes.js', `// Generated by scripts/build-lesson-minutes.mjs. Do not edit.\nexport const lessonMinutes = ${JSON.stringify(out)};\n`);
console.log(`wrote lessonMinutes.js (${Object.keys(out).length} lessons)`);
